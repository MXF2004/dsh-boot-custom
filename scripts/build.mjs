/**
 * Build entry point.
 *
 * Two artifacts, two compilers:
 *  - the host half is plain ESM: `tsc -p tsconfig.host.json` emits
 *    `lib/index.js` plus its imported `lib/host/*` and `lib/shared/*` modules;
 *  - the browser half is a single classic script: esbuild bundles
 *    `src/client/index.ts` as CommonJS, then the wrapper below emits the
 *    loader envelope the shell expects:
 *
 *        window.__ModuleLoader__.load({
 *          id: '<package-name>',
 *          factory: (require) => { … return module.exports }
 *        })
 *
 * React stays external and is resolved from the shell's platform module
 * table, exactly like the shipped client plugins.
 *
 * Usage: `node scripts/build.mjs [--client-only]`.
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const libDir = join(root, 'lib')
const tempFile = join(libDir, '.client.bundle.cjs')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const clientOnly = process.argv.includes('--client-only')

/** Run a local CLI with inherited stdio (capturing is unnecessary and slow). */
function run(command, args) {
  execFileSync(command, args, { cwd: root, stdio: 'inherit' })
}

/** Indent every line so the factory body reads like real source. */
function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? `${pad}${line}` : line))
    .join('\n')
}

/** Compile the host half with the project TypeScript. */
function buildHost() {
  const tsc = join(root, 'node_modules', 'typescript', 'bin', 'tsc')
  run(process.execPath, [tsc, '-p', join(root, 'tsconfig.host.json')])
  console.log('[build] host → lib/index.js')
}

/** Bundle the browser half and wrap it in the module-loader envelope. */
async function buildClient() {
  mkdirSync(libDir, { recursive: true })
  await build({
    entryPoints: [join(root, 'src', 'client', 'index.ts')],
    outfile: tempFile,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    jsx: 'transform',
    jsxFactory: 'h',
    jsxFragment: 'Fragment',
    external: ['react', 'react-dom', 'react/jsx-runtime'],
    legalComments: 'none',
    charset: 'utf8',
    // Startup matters: the shell evaluates this classic script before the boot
    // overlay mounts, so ship a compact bundle instead of readable source.
    minify: true,
    logLevel: 'info',
  })

  const bundle = readFileSync(tempFile, 'utf8')
  // The bundle is a classic script: the only global it touches at top level is
  // the loader facade the shell installs before any plugin script runs.
  const wrapped = [
    '/* Generated by scripts/build.mjs — do not edit. */',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(pkg.name)},`,
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    indent(bundle.trimEnd(), 4),
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n')
  writeFileSync(join(libDir, 'client.js'), wrapped, 'utf8')
  rmSync(tempFile, { force: true })
  console.log('[build] client → lib/client.js')
}

rmSync(libDir, { recursive: true, force: true })
if (!clientOnly) buildHost()
await buildClient()
console.log(`[build] ${pkg.name}@${pkg.version} ready`)
