/**
 * Packaging and runtime-contract tests.
 *
 * These assertions encode the hard requirements: one name across the patch,
 * the package and the host export; the client bundle envelope; the deprecated
 * `src/client.ts` path staying absent; the volatile Config anchor; and the
 * browser half exporting exactly `inject = ['slots']` + `apply`.
 */

import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'
import test from 'node:test'

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')

const pkg = JSON.parse(read('package.json'))
const patch = read('cordis.patch.yml')

test('package.json declares the bundle, client and entry contracts', () => {
  assert.equal(pkg.type, 'module')
  assert.equal(pkg.main, 'lib/index.js')
  assert.ok(pkg.files.includes('lib'))
  assert.ok(pkg.files.includes('src'))
  assert.ok(pkg.files.includes('cordis.patch.yml'), 'files must ship the bundle patch')
  assert.equal(pkg.dsh.bundle.patch, './cordis.patch.yml')
  assert.equal(pkg.dsh.client.platform, 'web')
  assert.equal(pkg.exports['./client'].default, './lib/client.js')
  assert.ok(String(pkg.dsh.engines.dsh).startsWith('>=0.1.7'))
  assert.match(pkg.dependencies['@deepseek-ai/schemastery'], /\^?3\.18\.[4-9]/)
})

test('the patch row id, package name and host export are identical', async () => {
  const id = /-\s*id:\s*([^\s]+)/.exec(patch)?.[1]
  const moduleName = /name:\s*['"]([^'"]+)['"]/.exec(patch)?.[1]
  assert.equal(id, pkg.name)
  assert.equal(moduleName, pkg.name)

  const host = await import('../lib/index.js')
  assert.equal(host.name, pkg.name)
  assert.equal(host.name, id)
  assert.equal(typeof host.apply, 'function')
  assert.ok(Array.isArray(host.inject))
  assert.ok(host.inject.includes('webServer'))
})

test('the host Config exposes at least one volatile anchor', async () => {
  const host = await import('../lib/index.js')
  const resolved = host.Config({ enabled: true })
  // A volatile field resolves to a stable reference carrying get().
  assert.equal(typeof resolved.enabled?.get, 'function')
  assert.equal(resolved.enabled.get(), true)
  // Non-volatile plain values would still be accepted by readField.
  const store = await import('../lib/host/store.js')
  assert.equal(store.readField(resolved.enabled), true)
  assert.equal(store.readField(true), true)
  assert.equal(store.readField(undefined), undefined)
})

test('the source layout uses src/client/index.ts, not src/client.ts', () => {
  assert.equal(existsSync(new URL('../src/client.ts', import.meta.url)), false)
  assert.equal(existsSync(new URL('../src/client/index.ts', import.meta.url)), true)
  assert.equal(existsSync(new URL('../src/index.ts', import.meta.url)), true)
  assert.equal(existsSync(new URL('../lib/index.js', import.meta.url)), true)
  assert.equal(existsSync(new URL('../lib/client.js', import.meta.url)), true)
})

test('the built client is a classic module-loader script at the expected id', () => {
  const client = read('lib/client.js')
  assert.ok(client.startsWith('/* Generated by scripts/build.mjs'))
  assert.ok(client.includes('window.__ModuleLoader__.load'))
  assert.ok(client.includes(`id: ${JSON.stringify(pkg.name)}`))
  assert.equal(client.includes('</script'), false)
  // Keep the startup script minified: a readable bundle is ~178 KB and slows
  // the first paint/eval; the minified artifact stays far below this guard.
  assert.ok(Buffer.byteLength(client, 'utf8') < 150_000, 'client bundle must stay minified')
})

test('the browser half exports inject = [slots] and apply', async () => {
  let captured
  globalThis.window = {
    __ModuleLoader__: {
      load(definition) {
        captured = definition
      },
    },
  }
  await import('../lib/client.js')
  assert.ok(captured !== undefined, 'the bundle registered a factory')
  assert.equal(captured.id, pkg.name)

  const React = {
    createElement: () => null,
    useState: () => [null, () => undefined],
    useEffect: () => undefined,
    useRef: () => ({ current: null }),
    Fragment: {},
  }
  const clientExports = captured.factory((request) => {
    if (request === 'react') return React
    throw new Error(`unexpected module request: ${request}`)
  })
  assert.deepEqual(clientExports.inject, ['slots'])
  assert.equal(typeof clientExports.apply, 'function')
})

test('the host build keeps schemastery external and emits ESM', () => {
  const host = read('lib/index.js')
  const schema = read('lib/host/schema.js')
  assert.ok(schema.includes('from \'@deepseek-ai/schemastery\''))
  assert.ok(host.includes('export { Config }'))
  assert.ok(
    host.includes('__BOOT_ANIM_FIRST_FRAME__') ||
      read('lib/host/first-frame.js').includes('__BOOT_ANIM_FIRST_FRAME__'),
  )
})
